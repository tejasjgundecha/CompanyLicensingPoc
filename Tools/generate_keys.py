#!/usr/bin/env python3
"""Generate a POC Ed25519 key pair with OpenSSL and embed the public key in the plugin.

The private key is written under Tools/keys/ and is NEVER copied into the Unreal application.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KEYS = ROOT / "Tools" / "keys"
PUBLIC_HEADER = (
    ROOT
    / "Plugins"
    / "CompanyLicensing"
    / "Source"
    / "CompanyLicensing"
    / "Private"
    / "LicensePublicKey.h"
)


def run(args: list[str]) -> None:
    subprocess.check_call(args)


def main() -> int:
    KEYS.mkdir(parents=True, exist_ok=True)
    private_pem = KEYS / "poc_ed25519_private.pem"
    public_pem = KEYS / "poc_ed25519_public.pem"
    public_der = KEYS / "poc_ed25519_public.der"

    if not private_pem.exists():
        run(["openssl", "genpkey", "-algorithm", "ED25519", "-out", str(private_pem)])
        print(f"Wrote {private_pem}")
    else:
        print(f"Keeping existing {private_pem}")

    run(["openssl", "pkey", "-in", str(private_pem), "-pubout", "-out", str(public_pem)])
    run(
        [
            "openssl",
            "pkey",
            "-in",
            str(public_pem),
            "-pubin",
            "-outform",
            "DER",
            "-out",
            str(public_der),
        ]
    )

    der = public_der.read_bytes()
    if len(der) < 32:
        print("Unexpected public key DER length", file=sys.stderr)
        return 1
    raw = der[-32:]

    import os
    share_a = os.urandom(32)
    share_b = os.urandom(32)
    share_c = bytes(r ^ a ^ b for r, a, b in zip(raw, share_a, share_b))

    def format_bytes(b: bytes) -> str:
        hex_bytes = ", ".join(f"0x{val:02x}" for val in b)
        grouped = []
        parts = hex_bytes.split(", ")
        for i in range(0, 32, 8):
            grouped.append("\t\t" + ", ".join(parts[i : i + 8]))
        return ",\n".join(grouped)

    body_a = format_bytes(share_a)
    body_b = format_bytes(share_b)
    body_c = format_bytes(share_c)

    PUBLIC_HEADER.write_text(
        f"""/**
 * Embedded Ed25519 public key for this POC.
 * Generated by Tools/generate_keys.py — never commit a private key into this header.
 *
 * Security Hardening (F5): The 32-byte Ed25519 public key is split into multiple
 * XOR-masked shares across distinct memory regions to prevent static binary searching
 * and trivial in-place .rdata binary substitution.
 */
#pragma once

#include "CoreMinimal.h"

namespace CompanyLicensing
{{
	inline const uint8 KeyShareA[32] = {{
{body_a}
	}};

	inline const uint8 KeyShareB[32] = {{
{body_b}
	}};

	inline const uint8 KeyShareC[32] = {{
{body_c}
	}};

	/** Reassembles the 32-byte public key in volatile stack memory. */
	FORCEINLINE void GetEmbeddedPublicKey(uint8 OutKey[32])
	{{
		for (int32 i = 0; i < 32; ++i)
		{{
			OutKey[i] = KeyShareA[i] ^ KeyShareB[i] ^ KeyShareC[i];
		}}
	}}
}}
""",
        encoding="utf-8",
    )
    print(f"Embedded split-share public key in {PUBLIC_HEADER}")
    print("Public key hex:", raw.hex())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
