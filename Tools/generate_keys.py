#!/usr/bin/env python3
"""Generate a POC Ed25519 key pair with OpenSSL and embed the public key in the plugin.

The private key is written under Tools/keys/ and is NEVER copied into the Unreal application.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KEYS = ROOT / "Tools" / "keys"
PUBLIC_HEADER = (
    ROOT
    / "Plugins"
    / "CompanyLicensing"
    / "Source"
    / "CompanyLicensing"
    / "Private"
    / "LicensePublicKey.h"
)


def run(args: list[str]) -> None:
    subprocess.check_call(args)


def main() -> int:
    KEYS.mkdir(parents=True, exist_ok=True)
    private_pem = KEYS / "poc_ed25519_private.pem"
    public_pem = KEYS / "poc_ed25519_public.pem"
    public_der = KEYS / "poc_ed25519_public.der"

    if not private_pem.exists():
        run(["openssl", "genpkey", "-algorithm", "ED25519", "-out", str(private_pem)])
        print(f"Wrote {private_pem}")
    else:
        print(f"Keeping existing {private_pem}")

    run(["openssl", "pkey", "-in", str(private_pem), "-pubout", "-out", str(public_pem)])
    run(
        [
            "openssl",
            "pkey",
            "-in",
            str(public_pem),
            "-pubin",
            "-outform",
            "DER",
            "-out",
            str(public_der),
        ]
    )

    der = public_der.read_bytes()
    if len(der) < 32:
        print("Unexpected public key DER length", file=sys.stderr)
        return 1
    raw = der[-32:]

    hex_bytes = ", ".join(f"0x{b:02x}" for b in raw)
    grouped = []
    parts = hex_bytes.split(", ")
    for i in range(0, 32, 8):
        grouped.append("\t\t" + ", ".join(parts[i : i + 8]))
    body = ",\n".join(grouped)

    PUBLIC_HEADER.write_text(
        f"""/**
 * Embedded Ed25519 public key for this POC.
 * Generated by Tools/generate_keys.py — never commit a private key into this header.
 *
 * 32-byte raw Ed25519 public key.
 */
#pragma once

#include "CoreMinimal.h"

namespace CompanyLicensing
{{
	inline const uint8 EmbeddedPublicKey[32] = {{
{body}
	}};
}}
""",
        encoding="utf-8",
    )
    print(f"Embedded public key in {PUBLIC_HEADER}")
    print("Public key hex:", raw.hex())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
